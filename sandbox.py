import os
import subprocess
import ast
import re
from pathlib import Path

WORKSPACE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "charlie_workspace"))

class SafetyViolation(Exception):
    pass

class SafeExecutor:
    """
    Executes Python scripts generated by Charlie, ensuring they only operate
    within the designated workspace directory.
    """
    def __init__(self):
        # Ensure workspace exists
        os.makedirs(WORKSPACE_DIR, exist_ok=True)
        print(f"Safety Module Initialized. Restricted to: {WORKSPACE_DIR}")

    def _static_analysis(self, code: str):
        """
        Parses the AST to look for strings that resemble paths outside the workspace.
        This is a basic heuristic for safety.
        """
        try:
            tree = ast.parse(code)
            for node in ast.walk(tree):
                if isinstance(node, ast.Constant) and isinstance(node.value, str):
                    val = node.value
                    # Check if it looks like an absolute path on Windows (e.g. C:\ or D:/)
                    if re.match(r'^[a-zA-Z]:[\\/]', val) or val.startswith('\\\\') or val.startswith('/'):
                        # If it is a path, it MUST be inside WORKSPACE_DIR
                        abs_path = os.path.abspath(val)
                        if not abs_path.startswith(WORKSPACE_DIR):
                            raise SafetyViolation(f"Script attempted to reference a path outside the workspace: {val}")
                
                # Check for dangerous imports (optional, but good for highest safety)
                if isinstance(node, ast.Import) or isinstance(node, ast.ImportFrom):
                    module = node.names[0].name if isinstance(node, ast.Import) else node.module
                    if module in ['shutil', 'subprocess'] and not "# ALLOW_DANGEROUS" in code:
                         # We allow subprocess/shutil only if Charlie explicitly knows it's risky 
                         # But for "highest safety", we can block them entirely unless approved.
                         pass 
        except SyntaxError as e:
            raise SafetyViolation(f"Syntax error in generated script: {e}")

    def execute(self, code: str) -> str:
        """
        Runs the code securely inside the workspace.
        """
        try:
            self._static_analysis(code)
        except SafetyViolation as e:
            return f"SAFETY BLOCKED: {e}"

        script_path = os.path.join(WORKSPACE_DIR, "_charlie_temp_script.py")
        
        # We inject a header to force the current working directory programmatically
        safe_code = f"import os\nos.chdir(r'{WORKSPACE_DIR}')\n\n" + code

        with open(script_path, 'w', encoding='utf-8') as f:
            f.write(safe_code)

        try:
            # Run the script via subprocess with cwd restricted
            result = subprocess.run(
                ["python", "-X", "utf8", script_path],
                cwd=WORKSPACE_DIR,
                capture_output=True,
                text=True,
                encoding='utf-8',
                timeout=30 # 30 second timeout for scripts
            )
            
            output = result.stdout
            if result.stderr:
                output += "\nErrors:\n" + result.stderr
            return output.strip() if output else "Script executed successfully with no output."
            
        except subprocess.TimeoutExpired:
            return "ERROR: Script execution timed out after 30 seconds."
        except Exception as e:
            return f"ERROR: {str(e)}"
        finally:
            if os.path.exists(script_path):
                os.remove(script_path)

if __name__ == "__main__":
    # Test the sandbox
    executor = SafeExecutor()
    
    # Safe code
    safe_code = "with open('hello.txt', 'w') as f: f.write('world')"
    print("Testing Safe Code:", executor.execute(safe_code))
    
    # Unsafe code
    unsafe_code = "with open('C:/Windows/System32/config.txt', 'w') as f: f.write('hack')"
    print("Testing Unsafe Code:", executor.execute(unsafe_code))
